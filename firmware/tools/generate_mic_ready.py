#!/usr/bin/env python3
"""Render a soft 75 ms metallic double tap, PCM16/16 kHz. No API calls."""
import math, struct, wave
from pathlib import Path
root=Path(__file__).resolve().parents[1]
rate=16000;audio=[]
for i in range(1200):
 t=i/rate;value=0.0
 for onset,gain in [(0,1.0),(.019,.42)]:
  x=t-onset
  if x>=0:
   attack=min(1,x/.0008)
   value+=gain*attack*sum(a*math.exp(-x/tau)*math.sin(2*math.pi*f*x) for f,a,tau in [(1730,1050,.010),(2917,760,.016),(4321,420,.008),(6383,160,.005)])
 value*=min(1,(.075-t)/.006)
 audio.append(round(value))
header='/* Generated by tools/generate_mic_ready.py: PCM16, mono, 16 kHz, 75 ms. */\n#pragma once\n#include <stdint.h>\nstatic const int16_t lumi_mic_ready_pcm[]={\n'
header+='\n'.join(' '+','.join(map(str,audio[i:i+16]))+',' for i in range(0,len(audio),16))+'\n};\n'
(root/'main/mic_ready_sound.h').write_text(header)
# Local preview is outside tracked firmware assets.
preview=Path('/Users/grpi/Work/lumi/diagnostics/sol-ultrafast/mic-ready.wav')
with wave.open(str(preview),'wb') as w:
 w.setparams((1,2,rate,0,'NONE','not compressed'));w.writeframes(struct.pack('<'+'h'*len(audio),*audio))
print('Generated 75 ms cue; peak:',max(map(abs,audio)))
